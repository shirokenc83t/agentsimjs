import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { it } from "vitest";
import { computeBodiesHash, computeDetmathCases, computeDrivesHash, computeProbeHash, GOLDEN_BODIES, GOLDEN_PROBE } from "../../packages/core/src/testing/golden-cases.ts";
import { StateHasher } from "../../packages/core/src/index.ts";
import { REFERENCE_TICKS, runReference } from "../../packages/scenarios/src/testing/reference-run.ts";
import { canonicalJson, hash32Hex } from "../../packages/scenarios/src/canonical.ts";
import { f2DiscoveryScenario, f2PriorReferenceScenario, f2TwentyAgentsScenario } from "../../packages/scenarios/src/presets/f2-presets.ts";
import { computeRequestHash, REQUEST_TICKS } from "../../packages/scenarios/src/testing/request-golden.ts";
import { computeSummaryHash, SUMMARY_TICKS } from "../../packages/scenarios/src/testing/topology-summary-golden.ts";
import { buildReferenceWorld } from "../../packages/spatial/src/index.ts";

// Regenerates packages/core/src/testing/golden.json in Node (V8). Run only deliberately:
//   UPDATE_GOLDEN=1 pnpm exec vitest run tools/golden
// Golden changes must be explained in the commit (CLAUDE.md: golden traces).
it.runIf(!!process.env["UPDATE_GOLDEN"])("update core golden fixture", () => {
  const golden = {
    $comment: "Generated by tools/golden/update-golden.test.ts in Node; must match in every engine (ADR-0023).",
    probe: { ...GOLDEN_PROBE, hash: computeProbeHash(GOLDEN_PROBE.seed, GOLDEN_PROBE.ticks) },
    bodies: { ...GOLDEN_BODIES, hash: computeBodiesHash(GOLDEN_BODIES.seed) },
    drives: computeDrivesHash(),
    detmath: computeDetmathCases(),
  };
  writeFileSync(resolve("packages/core/src/testing/golden.json"), JSON.stringify(golden, null, 1) + "\n");
});

// F1 reference scenario through the whole stack (d7).
it.runIf(!!process.env["UPDATE_GOLDEN"])("update reference-run golden fixture", async () => {
  const { checkpoints } = await runReference();
  const golden = {
    $comment: "Generated by tools/golden/update-golden.test.ts in Node; state hash every 100 ticks, must match in every engine.",
    ticks: REFERENCE_TICKS,
    checkpoints,
  };
  writeFileSync(resolve("packages/scenarios/src/testing/reference-run.golden.json"), JSON.stringify(golden, null, 1) + "\n");
});

// Topological layer summaries (ADR-0039 §6): byte-identical in every engine.
it.runIf(!!process.env["UPDATE_GOLDEN"])("update topology-summary golden fixture", async () => {
  const golden = {
    $comment: "Generated by tools/golden/update-golden.test.ts in Node; hash of every agent's space summary, must match in every engine.",
    ticks: SUMMARY_TICKS,
    summaryHash: await computeSummaryHash(),
  };
  writeFileSync(resolve("packages/scenarios/src/testing/topology-summary.golden.json"), JSON.stringify(golden, null, 1) + "\n");
});

// World hash of the 1 km² reference world (F1 f1): shared by the preset's Node test and the lab's e2e test.
it.runIf(!!process.env["UPDATE_GOLDEN"])("update reference-world golden fixture", () => {
  const h = new StateHasher();
  buildReferenceWorld().hashInto(h);
  const golden = { $comment: "Generated by tools/golden/update-golden.test.ts: grid hash of buildReferenceWorld().", worldHash: h.hex() };
  writeFileSync(resolve("packages/scenarios/src/presets/f1-reference-world.golden.json"), JSON.stringify(golden, null, 1) + "\n");
});

// Decision requests (ADR-0005 addition of 2026-10-11): the request sequence of the reference run, byte-identical in every engine.
it.runIf(!!process.env["UPDATE_GOLDEN"])("update request golden fixture", async () => {
  const r = await computeRequestHash();
  const golden = {
    $comment: "Generated by tools/golden/update-golden.test.ts in Node; hash of the decision requests of a 200-tick run, must match in every engine.",
    ticks: REQUEST_TICKS,
    requests: r.requests,
    requestHash: r.hash,
  };
  writeFileSync(resolve("packages/scenarios/src/testing/request.golden.json"), JSON.stringify(golden, null, 1) + "\n");
});

// F2 preset documents (M2e): content hashes of the demo scenarios the lab builds in the worker.
it.runIf(!!process.env["UPDATE_GOLDEN"])("update F2 presets golden fixture", () => {
  const golden = {
    $comment: "Generated by tools/golden/update-golden.test.ts: content hashes of the F2 preset scenario documents.",
    discovery: hash32Hex(canonicalJson(f2DiscoveryScenario())),
    agents20: hash32Hex(canonicalJson(f2TwentyAgentsScenario())),
    prior1km: hash32Hex(canonicalJson(f2PriorReferenceScenario())),
  };
  writeFileSync(resolve("packages/scenarios/src/presets/f2-presets.golden.json"), JSON.stringify(golden, null, 1) + "\n");
});
